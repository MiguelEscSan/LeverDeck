using System.Globalization;
using System.Reflection;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;
using System.Text.Json.Serialization.Metadata;
using LeverDeck.Protocol;
using LeverDeck.Protocol.Messages;
using LeverDeck.Protocol.Serialization;

namespace LeverDeck.ProtocolGen;

/// <summary>
/// Generates the TypeScript protocol types from the serializer contract itself (<see cref="ProtocolJsonContext"/>):
/// property names, nullability, enum strings and <c>kind</c>/<c>type</c> discriminators are read from the same
/// metadata that writes the JSON, so the types cannot drift from the wire. Output is deterministic: blocks are
/// sorted by name, union members keep their declaration order and lines end with LF.
/// </summary>
public static class TypeScriptGenerator
{
    public const string Header = "// Generated by LeverDeck.ProtocolGen — do not edit.";

    private const int MaxSingleLineLength = 120;

    private static readonly string[] _contractNamespaces = ["LeverDeck.Protocol.Dtos", "LeverDeck.Protocol.Messages"];

    /// <summary>File name → content, for every file of <c>web/src/app/core/protocol</c>.</summary>
    public static IReadOnlyDictionary<string, string> Generate() => new SortedDictionary<string, string>(StringComparer.Ordinal)
    {
        ["index.ts"] = $"{Header}\nexport * from './protocol';\n",
        ["protocol.ts"] = GenerateProtocol(),
    };

    private static string GenerateProtocol()
    {
        var types = typeof(Message).Assembly.GetExportedTypes()
            .Where(type => _contractNamespaces.Contains(type.Namespace))
            .OrderBy(type => type.Name, StringComparer.Ordinal)
            .ToArray();

        List<string> blocks =
        [
            $"export const PROTOCOL_VERSION = {ProtocolInfo.ProtocolVersion.ToString(CultureInfo.InvariantCulture)};",
            .. types.Where(type => type.IsEnum).Select(EnumBlock),
            .. types.Where(type => type.IsAbstract).Select(UnionBlock),
            .. types.Where(type => type is { IsClass: true, IsAbstract: false }).Select(InterfaceBlock),
        ];

        return $"{Header}\n\n{string.Join("\n\n", blocks)}\n";
    }

    private static string EnumBlock(Type enumType)
    {
        var typeInfo = TypeInfo(enumType);
        var values = Enum.GetValues(enumType)
            .Cast<object>()
            .Select(value => Literal(JsonSerializer.Deserialize<string>(JsonSerializer.Serialize(value, typeInfo))!));

        return Alias(enumType.Name, values);
    }

    private static string UnionBlock(Type baseType)
    {
        IEnumerable<Type> members = baseType == typeof(Message)
            ? MessageKinds.All.Select(entry => entry.Type)
            : TypeInfo(baseType).PolymorphismOptions?.DerivedTypes.Select(derived => derived.DerivedType)
                ?? throw new NotSupportedException($"{baseType.Name} is abstract but not polymorphic.");

        return Alias(baseType.Name, members.Select(member => member.Name));
    }

    private static string InterfaceBlock(Type type)
    {
        var fields = Discriminators(type).Concat(Properties(type)).ToArray();
        if (fields.Length == 0)
        {
            return $"export type {type.Name} = Record<string, never>;";
        }

        var builder = new StringBuilder();
        builder.Append(CultureInfo.InvariantCulture, $"export interface {type.Name} {{\n");
        foreach (var field in fields)
        {
            builder.Append(CultureInfo.InvariantCulture, $"  {field};\n");
        }

        return builder.Append('}').ToString();
    }

    /// <summary>The <c>kind</c> literal of a message and the <c>type</c> literal of a polymorphic member.</summary>
    private static IEnumerable<string> Discriminators(Type type)
    {
        if (MessageKinds.All.FirstOrDefault(entry => entry.Type.IsAssignableFrom(type)) is { Type: not null } kind)
        {
            yield return $"kind: {Literal(kind.Kind)}";
        }

        if (type.BaseType is { IsAbstract: true } baseType
            && TypeInfo(baseType).PolymorphismOptions is { } polymorphism
            && polymorphism.DerivedTypes.FirstOrDefault(derived => derived.DerivedType == type) is { DerivedType: not null } derived)
        {
            var id = Convert.ToString(derived.TypeDiscriminator, CultureInfo.InvariantCulture)!;
            yield return $"{polymorphism.TypeDiscriminatorPropertyName}: {Literal(id)}";
        }
    }

    private static IEnumerable<string> Properties(Type type)
    {
        foreach (var property in TypeInfo(type).Properties.Where(property => property.Get is not null))
        {
            var tsType = TsType(property.PropertyType);
            if (IsOmittedWhenNull(property))
            {
                yield return $"{property.Name}?: {tsType}";
            }
            else
            {
                yield return property.IsGetNullable ? $"{property.Name}: {tsType} | null" : $"{property.Name}: {tsType}";
            }
        }
    }

    private static bool IsOmittedWhenNull(JsonPropertyInfo property) =>
        property.AttributeProvider?
            .GetCustomAttributes(typeof(JsonIgnoreAttribute), inherit: true)
            .Cast<JsonIgnoreAttribute>()
            .Any(attribute => attribute.Condition is JsonIgnoreCondition.WhenWritingNull or JsonIgnoreCondition.WhenWritingDefault)
        ?? false;

    private static string TsType(Type type)
    {
        if (Nullable.GetUnderlyingType(type) is { } underlying)
        {
            return TsType(underlying);
        }

        if (type == typeof(string) || type == typeof(Guid) || type == typeof(DateTimeOffset))
        {
            return "string";
        }

        if (type == typeof(bool))
        {
            return "boolean";
        }

        if (type == typeof(int) || type == typeof(long) || type == typeof(double))
        {
            return "number";
        }

        if (type.IsGenericType && type.GetGenericTypeDefinition() == typeof(IReadOnlyList<>))
        {
            return $"{TsType(type.GetGenericArguments()[0])}[]";
        }

        if (_contractNamespaces.Contains(type.Namespace))
        {
            return type.Name;
        }

        throw new NotSupportedException($"No TypeScript mapping for {type.FullName}.");
    }

    private static string Alias(string name, IEnumerable<string> members)
    {
        var list = members.ToArray();
        var singleLine = $"export type {name} = {string.Join(" | ", list)};";
        return singleLine.Length <= MaxSingleLineLength
            ? singleLine
            : $"export type {name} =\n{string.Join("\n", list.Select(member => $"  | {member}"))};";
    }

    private static string Literal(string value) => $"'{value}'";

    private static JsonTypeInfo TypeInfo(Type type) =>
        ProtocolJsonContext.Default.GetTypeInfo(type)
        ?? throw new InvalidOperationException($"{type.Name} is missing from ProtocolJsonContext.");
}
